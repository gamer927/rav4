"""Header for the chip test (test/chip/chip_test.cpp): which AVR port and bit
each firmware pin really is on a Mega 2560.

Taken from the Arduino core's own pin table (variants/mega/pins_arduino.h)
and the firmware's pin list (namespace pin in tcu.ino), so the chip test
can't disagree with either.

  python3 tools/chip_pins.py > build/chip/pins.h
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORE = os.environ.get("ARDUINO_AVR", "/usr/share/arduino/hardware/arduino/avr")


def mega_pin_table():
    """Arduino pin number -> (port letter, bit), from the core's variant file."""
    text = open(os.path.join(CORE, "variants", "mega", "pins_arduino.h")).read()
    body = text.split("digital_pin_to_port_PGM[] = {")[1].split("};")[0]
    table = {}
    for port, bit, num in re.findall(r"P([A-L])\s*,\s*//\s*P[A-L]\s*(\d)\s*\*\*\s*(\d+)\s*\*\*", body):
        table[int(num)] = (port, int(bit))
    if len(table) != 70:
        sys.exit(f"chip_pins: read {len(table)} pins from the Mega variant, expected 70")
    return table


def firmware_pins():
    ino = open(os.path.join(ROOT, "firmware", "tcu", "tcu.ino")).read()
    block = ino.split("namespace pin {")[1].split("}")[0]
    return [(n, int(v[1:]) + 54 if v.startswith("A") else int(v))
            for n, v in re.findall(r"constexpr uint8_t (\w+) = (A?\d+);", block)]


def main():
    table = mega_pin_table()
    out = ["// Generated by tools/chip_pins.py from the Arduino core's Mega pin table",
           "// and tcu.ino's pin list. Do not edit.", "#pragma once"]
    for name, num in firmware_pins():
        port, bit = table[num]
        out.append(f"#define PIN_{name} {num}  // P{port}{bit}")
        out.append(f"#define PIN_{name}_PORT '{port}'")
        out.append(f"#define PIN_{name}_BIT {bit}")
        if num >= 54:
            out.append(f"#define PIN_{name}_ADC {num - 54}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
